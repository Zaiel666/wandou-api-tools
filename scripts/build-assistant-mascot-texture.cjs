/* Package the existing first pose for WebGL on both file: and http: pages. */
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('../desktop-client/node_modules/sharp');

(async () => {
  const assets = path.resolve(__dirname, '../app/assets');
  const source = sharp(path.join(assets, 'pea-assistant-sprite-v2.png'));
  const metadata = await source.metadata();
  const image = await source.extract({
    left:0, top:0, width:metadata.width/2, height:metadata.height/2
  }).resize(396, 396).webp({quality:94, alphaQuality:100, effort:6}).toBuffer();
  fs.writeFileSync(path.join(assets, 'pea-assistant-portrait.js'),
    '/* Generated by scripts/build-assistant-mascot-texture.cjs; original first pose, no new artwork. */\n' +
    'window.WandouMascotPortrait = "data:image/webp;base64,' + image.toString('base64') + '";\n');
  console.log(`Packaged mascot portrait: ${image.length} bytes`);
})().catch(error => { console.error(error); process.exitCode = 1; });
